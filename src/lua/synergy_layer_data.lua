-- O GGPKData do PoB chama `cd "<dir>\" && bun_extract_file.exe ...`: o `\"` do fim e o espaço no caminho quebram no
-- cmd. Mesma extração, com o caminho do executável inteiro e `cd /d` sem barra no fim.
common.classes.GGPKData.ExtractFilesWithBunFromTable = function(self, fileTable, useRegex)
  local manifest = self.oozPath .. "extract_list.txt"
  local f = assert(io.open(manifest, "w"))
  for _, fname in ipairs(fileTable) do f:write(string.lower(fname), "\n") end
  f:close()
  local dir = self.oozPath:gsub("\\$", "")
  local cmd = 'cd /d "' .. dir .. '" && "' .. self.oozPath .. 'bun_extract_file.exe" extract-files '
    .. (useRegex and "--regex " or "") .. '"' .. self.path .. '" . < "' .. manifest .. '"'
  ConPrintf("%s", cmd)
  os.execute(cmd)
  os.remove(manifest)
end

-- Mesmas funções que o Export/Main.lua do PoB dá aos scripts.
function processTemplateFile(name, inDir, outDir, directiveTable)
  local state = {}
  local out = io.open(outDir .. name .. ".lua", "w")
  out:write("-- This file is automatically generated, do not edit!\n")
  for line in io.lines(inDir .. name .. ".txt") do
    local spec, args = line:match("#(%a+) ?(.*)")
    if spec then
      if directiveTable[spec] then directiveTable[spec](state, args, out)
      else printf("Unknown directive '%s'", spec) end
    else
      if line:match("^%-%-") or line:match("^local") or line == "" then out:write(line, "\n")
      elseif line:match("^legacy") then out:write("\t" .. line, ",\n")
      else out:write("\t\t\t" .. line, "\n") end
    end
  end
  out:close()
end
function dat(name)
  name = name:lower()
  if not main.datFileByName[name] then error(name .. ".dat not found") end
  return main.datFileByName[name]
end
function getFile(name)
  name = name:lower()
  if not main.ggpk.txt[name] then
    local f = io.open(main.ggpk.oozPath .. name, "rb")
    if f then main.ggpk.txt[name] = f:read("*all"); f:close()
    else ConPrintf("Cannot Find File: %s", main.ggpk.oozPath .. name) end
  end
  return main.ggpk.txt[name]
end

