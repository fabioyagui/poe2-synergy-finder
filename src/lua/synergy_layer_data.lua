function NewFileSearch(pattern)
  local dir = winpath(pattern):match("^(.*)\\[^\\]*$") or "."
  local names = {}
  local h = io.popen('dir "' .. winpath(pattern) .. '" /b /a-d 2>nul')
  for line in h:lines() do line = line:gsub("\r$", ""); if line ~= "" then names[#names + 1] = line end end
  h:close()
  if #names == 0 then return nil end
  local i = 1
  return {
    GetFileName = function() return names[i] end,
    NextFile = function() i = i + 1; return names[i] ~= nil end,
    GetFileSize = function()
      local f = io.open(dir .. "\\" .. names[i], "rb"); if not f then return 0 end
      local n = f:seek("end"); f:close(); return n
    end,
  }
end
function PCall(func, ...)
  local r = { pcall(func, ...) }
  if r[1] then table.remove(r, 1); return nil, unpack(r) end
  return r[2]
end
function LoadModule(fileName, ...)
  if not fileName:match("%.lua") then fileName = fileName .. ".lua" end
  local func, err = loadfile(fileName)
  if not func then error("LoadModule() error loading '" .. fileName .. "': " .. err) end
  return func(...)
end
function PLoadModule(fileName, ...)
  if not fileName:match("%.lua") then fileName = fileName .. ".lua" end
  local func, err = loadfile(fileName)
  if not func then return "PLoadModule() error loading '" .. fileName .. "': " .. err end
  return PCall(func, ...)
end

